import ipaddress
import logging
from collections.abc import Mapping, Sequence
from enum import Enum
from urllib.parse import unquote, urlsplit

from pydantic import Field, field_validator

from frigate.util.env import EnvString, UnknownVariableError, substitute_frigate_vars

from ..base import FrigateBaseModel
from .objects import DEFAULT_TRACKED_OBJECTS

__all__ = ["OnvifConfig", "PtzAutotrackConfig", "ZoomingModeEnum"]

logger = logging.getLogger(__name__)


class ZoomingModeEnum(str, Enum):
    disabled = "disabled"
    absolute = "absolute"
    relative = "relative"


class PtzAutotrackConfig(FrigateBaseModel):
    enabled: bool = Field(
        default=False,
        title="Enable Autotracking",
        description="Enable or disable automatic PTZ camera tracking of detected objects.",
    )
    calibrate_on_startup: bool = Field(
        default=False,
        title="Calibrate on start",
        description="Measure PTZ motor speeds on startup to improve tracking accuracy. Frigate will update config with movement_weights after calibration.",
    )
    zooming: ZoomingModeEnum = Field(
        default=ZoomingModeEnum.disabled,
        title="Zoom mode",
        description="Control zoom behavior: disabled (pan/tilt only), absolute (most compatible), or relative (concurrent pan/tilt/zoom).",
    )
    zoom_factor: float = Field(
        default=0.3,
        title="Zoom factor",
        description="Control zoom level on tracked objects. Lower values keep more scene in view; higher values zoom in closer but may lose tracking. Values between 0.1 and 0.75.",
        ge=0.1,
        le=0.75,
    )
    track: list[str] = Field(
        default=DEFAULT_TRACKED_OBJECTS,
        title="Tracked objects",
        description="List of object types that should trigger autotracking.",
    )
    required_zones: list[str] = Field(
        default_factory=list,
        title="Required zones",
        description="Objects must enter one of these zones before autotracking begins.",
    )
    return_preset: str = Field(
        default="home",
        title="Return preset",
        description="ONVIF preset name configured in camera firmware to return to after tracking ends.",
    )
    timeout: int = Field(
        default=10,
        title="Return timeout",
        description="Wait this many seconds after losing tracking before returning camera to preset position.",
    )
    movement_weights: str | list[str] | None = Field(
        default_factory=list,
        title="Movement weights",
        description="Calibration values automatically generated by camera calibration. Do not modify manually.",
    )
    enabled_in_config: bool | None = Field(
        default=None,
        title="Original autotrack state",
        description="Internal field to track whether autotracking was enabled in configuration.",
    )

    @field_validator("movement_weights", mode="before")
    @classmethod
    def validate_weights(cls, v):
        if v is None:
            return None

        if isinstance(v, str):
            weights = list(map(str, map(float, v.split(","))))
        elif isinstance(v, list):
            weights = [str(float(val)) for val in v]
        else:
            raise ValueError("Invalid type for movement_weights")

        if len(weights) != 6:
            raise ValueError(
                "movement_weights must have exactly 6 floats, remove this line from your config and run autotracking calibration"
            )

        return weights


class OnvifConfig(FrigateBaseModel):
    host: EnvString = Field(
        default="",
        title="ONVIF host",
        description="Host (and optional scheme) for the ONVIF service for this camera. When empty, inferred from an unambiguous camera RTSP source, including local go2rtc restreams.",
    )
    port: int = Field(
        default=8000,
        title="ONVIF port",
        description="Port number for the ONVIF service.",
    )
    user: EnvString | None = Field(
        default=None,
        title="ONVIF username",
        description="Username for ONVIF authentication; some devices require a separate ONVIF account. When empty, inferred from the matching camera RTSP source.",
    )
    password: EnvString | None = Field(
        default=None,
        title="ONVIF password",
        description="Password for ONVIF authentication. When empty, inferred from the matching camera RTSP account. Explicit credentials are never overwritten.",
    )
    tls_insecure: bool = Field(
        default=False,
        title="Disable TLS verify",
        description="Skip TLS verification and disable digest auth for ONVIF (unsafe; use in safe networks only).",
    )
    profile: str | None = Field(
        default=None,
        title="ONVIF profile",
        description="Specific ONVIF media profile to use for PTZ control, matched by token or name. If not set, the first profile with valid PTZ configuration is selected automatically.",
    )
    recording_profile: str | None = Field(
        default=None,
        min_length=1,
        max_length=256,
        title="Recording source media profile",
        description="Explicit Media1 profile token for camera SD search and replay. This is separate from the PTZ profile. SD access fails closed until all recording source binding fields are saved.",
    )
    recording_video_source_token: str | None = Field(
        default=None,
        min_length=1,
        max_length=256,
        title="Recording physical video source",
        description="Camera-reported physical SourceToken belonging to the selected recording media profile. Revalidated on every SD search and replay session creation.",
    )
    recording_source_ref: str | None = Field(
        default=None,
        pattern=r"^[a-f0-9]{64}$",
        title="Recording source reference",
        description="Opaque reference discovered by an administrator from camera recording SourceId metadata. It binds SD recordings to this logical camera without exposing private source URIs. Never copy this binding to a different lens.",
    )
    autotracking: PtzAutotrackConfig = Field(
        default_factory=PtzAutotrackConfig,
        title="Autotracking",
        description="Automatically track moving objects and keep them centered in the frame using PTZ camera movements.",
    )
    ignore_time_mismatch: bool = Field(
        default=False,
        title="Ignore time mismatch",
        description="Ignore time synchronization differences between camera and Frigate server for ONVIF communication.",
    )


def infer_onvif_connection(
    onvif: OnvifConfig,
    input_paths: Sequence[str],
    streams: Mapping[str, object],
    camera_name: str,
) -> None:
    """Fill missing connection fields from unambiguous upstream RTSP metadata."""
    if onvif.host and onvif.user and onvif.password:
        return
    candidates: set[tuple[str, str | None, str | None]] = set()
    visited: set[str] = set()

    def resolve(source: str, depth: int = 0) -> None:
        if source in visited or depth > 16:
            return
        visited.add(source)
        if source.startswith("ffmpeg:"):
            resolve(source[len("ffmpeg:") :].split("#", 1)[0], depth + 1)
            return
        if source in streams:
            values = streams[source]
            for value in values if isinstance(values, list) else [values]:
                if isinstance(value, str):
                    try:
                        resolved = substitute_frigate_vars(value)
                    except UnknownVariableError:
                        logger.warning(
                            "Cannot infer ONVIF connection for %s: upstream stream references an unset variable",
                            camera_name,
                        )
                        continue
                    resolve(resolved, depth + 1)
            return
        try:
            parsed = urlsplit(source)
            host = parsed.hostname
        except ValueError:
            logger.warning(
                "Cannot infer ONVIF connection from an invalid URL for %s", camera_name
            )
            return
        if parsed.scheme not in {"rtsp", "rtsps"} or not host:
            return
        local = host.lower() == "localhost"
        if not local:
            try:
                local = ipaddress.ip_address(host).is_loopback
            except ValueError:
                local = False
        if local:
            resolve(unquote(parsed.path.lstrip("/")), depth + 1)
            return
        try:
            normalized_host = ipaddress.ip_address(host).compressed
        except ValueError:
            normalized_host = host.lower()
        candidates.add(
            (
                normalized_host,
                unquote(parsed.username) if parsed.username else None,
                unquote(parsed.password) if parsed.password else None,
            )
        )

    for path in input_paths:
        resolve(path)
    if onvif.host:
        try:
            expected = ipaddress.ip_address(onvif.host.strip("[]")).compressed
        except ValueError:
            try:
                expected = urlsplit(
                    onvif.host if "://" in onvif.host else f"//{onvif.host}"
                ).hostname
            except ValueError:
                logger.warning(
                    "Cannot infer credentials for an invalid ONVIF host for %s",
                    camera_name,
                )
                return
        candidates = {
            value for value in candidates if value[0] == (expected or "").lower()
        }
    hosts = {value[0] for value in candidates}
    if len(hosts) != 1:
        if len(hosts) > 1:
            logger.warning(
                "Multiple RTSP hosts found for %s; set ONVIF connection explicitly",
                camera_name,
            )
        return
    if not onvif.host:
        onvif.host = next(iter(hosts))
    if onvif.user:
        candidates = {value for value in candidates if value[1] == onvif.user}
    accounts = {(user, password) for _, user, password in candidates if user}
    if len(accounts) != 1:
        if len(accounts) > 1:
            logger.warning(
                "Multiple RTSP accounts found for %s; set ONVIF credentials explicitly",
                camera_name,
            )
        return
    user, password = next(iter(accounts))
    if not onvif.user:
        onvif.user = user
    if not onvif.password and password:
        onvif.password = password
