"""Viewer-owned WebRTC sessions with bounded, on-demand media-engine pulls."""

import asyncio
import base64
import hashlib
import hmac
import json
import logging
import time
import uuid
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Literal
from urllib.parse import quote

import aiohttp
from pydantic import BaseModel, ConfigDict, Field

from frigate.config.live_webrtc import LiveWebRTCConfig

if TYPE_CHECKING:
    from frigate.config import FrigateConfig

logger = logging.getLogger(__name__)
RUNTIME = Path("/dev/shm/ovenmediaengine")
DETAIL_HEIGHTS = (720, 1080, 2160)
DETAIL_BITRATES = {720: 1200, 1080: 2500, 2160: 8000}


class LiveWebRTCError(Exception):
    """A public, nonsecret media-session failure."""

    def __init__(self, status: int, code: str):
        super().__init__(code)
        self.status = status
        self.code = code


class ViewerBody(BaseModel):
    """Viewers select a bounded quality, never camera URLs or media destinations."""

    model_config = ConfigDict(extra="forbid")
    view: Literal["grid", "detail"] = "detail"
    height: Literal[360, 720, 1080, 2160] | None = None
    max_height: Literal[720, 1080, 2160] = 1080
    audio: bool = True
    force_relay: bool = False


class AnswerBody(BaseModel):
    model_config = ConfigDict(extra="forbid")
    type: Literal["answer"] = "answer"
    sdp: str = Field(min_length=10, max_length=128_000)


class IceCandidate(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)
    candidate: str = Field(max_length=4096, pattern=r"^[^\r\n\x00]*$")
    sdp_m_line_index: int = Field(alias="sdpMLineIndex", ge=0, le=64)
    sdp_mid: str | None = Field(default=None, alias="sdpMid", max_length=128)
    username_fragment: str | None = Field(
        default=None, alias="usernameFragment", max_length=256
    )


class CandidateBody(BaseModel):
    model_config = ConfigDict(extra="forbid")
    candidates: list[IceCandidate] = Field(max_length=32)


class QualityBody(BaseModel):
    model_config = ConfigDict(extra="forbid")
    height: Literal[360, 720, 1080, 2160] | None = None


@dataclass
class MediaGroup:
    camera: str
    app: str
    stream: str
    view: str
    users: int = 0
    started: bool = False
    closing: bool = False
    lock: asyncio.Lock = field(default_factory=asyncio.Lock)


@dataclass
class ViewerSession:
    identifier: str
    owner: str
    camera: str
    group: MediaGroup
    deadline: float
    hard_deadline: float
    socket: aiohttp.ClientWebSocketResponse
    peer_id: int
    remote_peer_id: int
    offer: dict
    candidates: list[dict]
    heights: tuple[int, ...] = ()
    initial_height: int | None = None
    answered: bool = False
    watcher: asyncio.Task | None = None
    lock: asyncio.Lock = field(default_factory=asyncio.Lock)


def application_name(view: str, maximum: int, audio: bool) -> str:
    """Use only the dedicated applications generated by Frigate's bootstrap."""
    return f"frigate_{'grid' if view == 'grid' else f'detail_{maximum}'}_{int(audio)}"


def turn_ice_servers(
    settings: LiveWebRTCConfig, secret: str, identifier: str, now: float
) -> list[dict]:
    """Issue expiring Coturn REST credentials without exposing its shared secret."""
    relay = settings.turn
    if not relay.enabled:
        return []
    expires = int(now) + relay.credential_seconds
    username = f"{expires}:{identifier}"
    credential = base64.b64encode(
        hmac.new(secret.encode(), username.encode(), hashlib.sha1).digest()
    ).decode()
    urls = [
        f"turn:{relay.hostname}:{relay.port}?transport=udp",
        f"turn:{relay.hostname}:{relay.port}?transport=tcp",
    ]
    if relay.tls:
        urls.append(f"turns:{relay.hostname}:{relay.tls_port}?transport=tcp")
    return [{"urls": urls, "username": username, "credential": credential}]


class OvenTransport:
    """Only loopback REST and signaling are reachable through this adapter."""

    def __init__(self, token: str):
        self.http = aiohttp.ClientSession(
            headers={
                "Authorization": "Basic " + base64.b64encode(token.encode()).decode()
            },
            timeout=aiohttp.ClientTimeout(total=15, connect=3),
            trust_env=False,
        )

    @staticmethod
    def stream_url(group: MediaGroup) -> str:
        """Address only a server-generated stream in a dedicated local application."""
        return f"http://127.0.0.1:8081/v1/vhosts/default/apps/{group.app}/streams"

    async def create_pull(self, group: MediaGroup, source: str) -> None:
        """Create a nonpersistent camera pull only after viewer admission."""
        try:
            async with self.http.post(
                self.stream_url(group),
                json={
                    "name": group.stream,
                    "urls": [f"rtsp://127.0.0.1:8554/{quote(source, safe='')}"],
                    "properties": {
                        "persistent": False,
                        "unusedStreamDeletionTimeoutMs": 30000,
                        "retryCount": 0,
                    },
                },
                allow_redirects=False,
            ) as response:
                if response.status != 201:
                    logger.warning(
                        "Live media pull rejected with status %s", response.status
                    )
                    raise LiveWebRTCError(503, "live_webrtc_source_unavailable")
        except (aiohttp.ClientError, TimeoutError):
            logger.warning("Live media pull is unavailable")
            raise LiveWebRTCError(503, "live_webrtc_engine_unavailable") from None

    async def delete_pull(self, group: MediaGroup) -> None:
        """A missing stream is already stopped; all other errors remain explicit."""
        try:
            async with self.http.delete(
                self.stream_url(group) + "/" + group.stream, allow_redirects=False
            ) as response:
                if response.status not in (200, 202, 204, 404):
                    raise LiveWebRTCError(503, "live_webrtc_cleanup_pending")
        except (aiohttp.ClientError, TimeoutError):
            raise LiveWebRTCError(503, "live_webrtc_cleanup_pending") from None

    async def offer(
        self, group: MediaGroup
    ) -> tuple[aiohttp.ClientWebSocketResponse, dict]:
        """Use the pinned OME offer/answer protocol, never expose its control socket."""
        socket = None
        try:
            socket = await self.http.ws_connect(
                f"http://127.0.0.1:3333/{group.app}/{group.stream}/master?transport=udp",
                max_msg_size=192_000,
                heartbeat=10,
                origin="http://127.0.0.1",
                headers={"User-Agent": "FrigateLiveWebRTC/1"},
            )
            await socket.send_json({"command": "request_offer"})
            message = await asyncio.wait_for(socket.receive_json(), timeout=12)
            if (
                message.get("command") != "offer"
                or message.get("code") != 200
                or type(message.get("id")) is not int
                or type(message.get("peer_id")) is not int
                or message.get("sdp", {}).get("type") != "offer"
                or not isinstance(message.get("sdp", {}).get("sdp"), str)
                or len(message["sdp"]["sdp"]) > 128_000
                or not isinstance(message.get("candidates"), list)
                or len(message["candidates"]) > 32
            ):
                raise LiveWebRTCError(503, "live_webrtc_invalid_offer")
            return socket, message
        except (
            aiohttp.ClientError,
            TimeoutError,
            ValueError,
            TypeError,
            AttributeError,
        ):
            logger.warning("Live media signaling is unavailable or invalid")
            if socket is not None:
                await socket.close()
            raise LiveWebRTCError(503, "live_webrtc_signaling_unavailable") from None
        except LiveWebRTCError:
            if socket is not None:
                await socket.close()
            raise

    async def close(self) -> None:
        """Close the engine's private HTTP pool."""
        await self.http.close()


class LiveWebRTCManager:
    """Coalesce per-camera viewing work and terminate it after the last viewer."""

    def __init__(
        self,
        config: Callable[[], "FrigateConfig"],
        *,
        runtime: Path = RUNTIME,
        clock: Callable[[], float] = time.time,
        transport: OvenTransport | None = None,
    ):
        self.config = config
        self.runtime = runtime
        self.clock = clock
        self.transport = transport
        self.groups: dict[tuple[str, str], MediaGroup] = {}
        self.sessions: dict[str, ViewerSession] = {}
        self.admission = asyncio.Lock()
        self.pending = 0
        # Recorded viewers share these exact viewer and detail-encoder budgets.
        # Failed cleanup keeps its encoder reservation until removal is confirmed.
        self.external_viewers: set[str] = set()
        self.external_encoders: set[str] = set()
        self.creating: set[asyncio.Task] = set()
        self.settings: LiveWebRTCConfig | None = None
        self.turn_secret = ""
        self.worker: asyncio.Task | None = None
        self.closed = False

    async def start(self) -> None:
        """Start lease maintenance without opening any camera or media pull."""
        settings = self.config().live_webrtc
        if settings.enabled:
            try:
                metadata = await asyncio.to_thread(
                    lambda: json.loads((self.runtime / "runtime.json").read_text())
                )
                if (
                    metadata["settings_sha256"]
                    != hashlib.sha256(settings.model_dump_json().encode()).hexdigest()
                ):
                    raise ValueError("Media settings require restart")
                token = metadata["api_token"]
                secret = metadata["turn_secret"]
                if not isinstance(token, str) or len(token) < 32:
                    raise ValueError("Invalid media credentials")
                if not isinstance(secret, str) or len(secret) < 32:
                    raise ValueError("Invalid relay credentials")
            except (OSError, ValueError, KeyError, TypeError):
                logger.error(
                    "WebRTC runtime is not ready; check configuration and restart"
                )
            else:
                self.settings = settings.model_copy(deep=True)
                self.turn_secret = secret
                if self.transport is None:
                    self.transport = OvenTransport(token)
        self.worker = asyncio.create_task(self._maintain())

    def available(self) -> bool:
        """Do not advertise a live path before its supervised runtime is configured."""
        return (
            not self.closed
            and self.settings is not None
            and self.settings == self.config().live_webrtc
        )

    async def reserve_external(self, identifier: str, *, encoder: bool = False) -> None:
        """Admit a recorded viewer or encoder against the live admission budgets."""
        async with self.admission:
            if not self.available():
                raise LiveWebRTCError(503, "live_webrtc_restart_required")
            settings = self.settings
            if encoder:
                used = sum(group.view == "detail" for group in self.groups.values())
                if used + len(self.external_encoders) >= settings.max_detail_cameras:
                    raise LiveWebRTCError(429, "live_webrtc_encoding_capacity")
                self.external_encoders.add(identifier)
            else:
                if (
                    self.pending + len(self.sessions) + len(self.external_viewers)
                    >= settings.max_viewers
                ):
                    raise LiveWebRTCError(429, "live_webrtc_viewer_capacity")
                self.external_viewers.add(identifier)

    async def release_external(self, identifier: str) -> None:
        """Release only resources whose readers and native channels have stopped."""
        async with self.admission:
            self.external_viewers.discard(identifier)
            self.external_encoders.discard(identifier)

    async def _release_group(self, group: MediaGroup) -> None:
        async with group.lock:
            group.users -= 1
            if group.users:
                return
            group.closing = True
            try:
                await self.transport.delete_pull(group)
            except LiveWebRTCError:
                logger.warning("Live media cleanup pending for %s", group.camera)
                return
            async with self.admission:
                self.groups.pop((group.camera, group.app), None)

    async def create(
        self, camera: str, owner: str, body: ViewerBody, auth_expires: float
    ) -> dict:
        """Reserve CPU/viewer capacity before pulling any source stream."""
        if not self.available():
            raise LiveWebRTCError(503, "live_webrtc_restart_required")
        config = self.config()
        selected = config.cameras.get(camera)
        if selected is None or not selected.enabled:
            raise LiveWebRTCError(404, "camera_not_available")
        settings = self.settings
        if settings is None:
            raise LiveWebRTCError(503, "live_webrtc_restart_required")
        maximum = min(body.max_height, settings.max_height)
        heights = (
            [settings.grid_height]
            if body.view == "grid"
            else [height for height in DETAIL_HEIGHTS if height <= maximum]
        )
        if body.height is not None and body.height not in heights:
            raise LiveWebRTCError(404, "live_webrtc_rendition_not_available")
        if body.force_relay and not settings.turn.enabled:
            raise LiveWebRTCError(409, "live_webrtc_relay_not_configured")
        source = selected.live.transcode.source or camera
        if source not in config.go2rtc.streams or "_transcode_" in source:
            raise LiveWebRTCError(503, "live_webrtc_source_not_configured")
        app = application_name(body.view, maximum, body.audio)
        task = asyncio.current_task()
        if task is None:
            raise RuntimeError("Live viewing requires an asyncio task")
        async with self.admission:
            if self.closed:
                raise LiveWebRTCError(503, "live_webrtc_restart_required")
            if (
                self.pending + len(self.sessions) + len(self.external_viewers)
                >= settings.max_viewers
            ):
                raise LiveWebRTCError(429, "live_webrtc_viewer_capacity")
            group = self.groups.get((camera, app))
            if group is not None and group.closing:
                raise LiveWebRTCError(503, "live_webrtc_cleanup_pending")
            if group is None:
                limit = (
                    settings.max_grid_cameras
                    if body.view == "grid"
                    else settings.max_detail_cameras
                )
                if (
                    sum(item.view == body.view for item in self.groups.values())
                    + (len(self.external_encoders) if body.view == "detail" else 0)
                    >= limit
                ):
                    raise LiveWebRTCError(429, "live_webrtc_encoding_capacity")
                group = MediaGroup(camera, app, f"fv_{uuid.uuid4().hex}", body.view)
                self.groups[(camera, app)] = group
            group.users += 1
            self.pending += 1
            self.creating.add(task)
        socket = None
        admitted = False
        try:
            async with group.lock:
                if group.closing:
                    raise LiveWebRTCError(503, "live_webrtc_cleanup_pending")
                if not group.started:
                    try:
                        await self.transport.create_pull(group, source)
                    except LiveWebRTCError:
                        group.closing = True
                        raise
                    group.started = True
            socket, message = await self.transport.offer(group)
            identifier = str(uuid.uuid4())
            now = self.clock()
            hard_deadline = min(now + settings.max_session_seconds, auth_expires)
            if hard_deadline <= now or not self.available():
                raise LiveWebRTCError(401, "live_webrtc_session_expired")
            session = ViewerSession(
                identifier,
                owner,
                camera,
                group,
                min(now + settings.lease_seconds, hard_deadline),
                hard_deadline,
                socket,
                message["id"],
                message["peer_id"],
                message["sdp"],
                message["candidates"],
                heights=tuple(heights),
                initial_height=body.height,
            )
            async with self.admission:
                self.sessions[identifier] = session
                admitted = True
            session.watcher = asyncio.create_task(self._watch(session))
            response = self._metadata(session)
            response.update(
                offer=session.offer,
                ice_candidates=session.candidates,
                ice_transport_policy="relay" if body.force_relay else "all",
                renditions=[
                    {
                        "height": height,
                        "bitrate": 500
                        if body.view == "grid"
                        else DETAIL_BITRATES[height],
                    }
                    for height in heights
                ],
                initial_height=body.height,
            )
            return response
        finally:
            async with self.admission:
                self.pending -= 1
            if not admitted:
                if socket is not None:
                    await socket.close()
                await self._release_group(group)
            self.creating.discard(task)

    def _metadata(self, session: ViewerSession) -> dict:
        base = f"{quote(session.camera, safe='')}/live/webrtc/sessions/{session.identifier}"
        return {
            "version": 1,
            "protocol": "webrtc",
            "session_id": session.identifier,
            "expires_at": session.deadline,
            "heartbeat_seconds": max(5, self.settings.lease_seconds // 3),
            "answer_url": base + "/answer",
            "candidates_url": base + "/candidates",
            "heartbeat_url": base,
            "close_url": base,
            "quality_url": base + "/quality",
            "ice_servers": turn_ice_servers(
                self.settings, self.turn_secret, session.identifier, self.clock()
            ),
        }

    def owned(self, camera: str, owner: str, identifier: str) -> ViewerSession:
        """Never let an owner-selected ID operate on another user's media."""
        session = self.sessions.get(identifier)
        if session is None or session.owner != owner or session.camera != camera:
            raise LiveWebRTCError(404, "live_webrtc_session_not_found")
        if session.deadline <= self.clock() or not self.available():
            raise LiveWebRTCError(410, "live_webrtc_session_expired")
        return session

    async def answer(
        self, camera: str, owner: str, identifier: str, body: AnswerBody
    ) -> None:
        """Accept exactly one answer for the server-owned peer connection."""
        session = self.owned(camera, owner, identifier)
        async with session.lock:
            if session.answered:
                raise LiveWebRTCError(409, "live_webrtc_already_answered")
            try:
                await session.socket.send_json(
                    {
                        "command": "answer",
                        "id": session.peer_id,
                        "peer_id": session.remote_peer_id,
                        "sdp": body.model_dump(),
                    }
                )
            except (aiohttp.ClientError, ConnectionError):
                raise LiveWebRTCError(503, "live_webrtc_signaling_closed") from None
            session.answered = True
            await self._quality(session, session.initial_height)

    async def _quality(self, session: ViewerSession, height: int | None) -> None:
        if height is not None and height not in session.heights:
            raise LiveWebRTCError(404, "live_webrtc_rendition_not_available")
        message = {
            "command": "change_rendition",
            "id": session.peer_id,
            "auto": height is None,
        }
        if height is not None:
            message["rendition_name"] = f"{height}p"
        try:
            await session.socket.send_json(message)
        except (aiohttp.ClientError, ConnectionError):
            raise LiveWebRTCError(503, "live_webrtc_signaling_closed") from None

    async def quality(
        self, camera: str, owner: str, identifier: str, body: QualityBody
    ) -> None:
        """Switch an allowed rendition without rebuilding its peer connection."""
        session = self.owned(camera, owner, identifier)
        async with session.lock:
            if not session.answered:
                raise LiveWebRTCError(409, "live_webrtc_answer_required")
            await self._quality(session, body.height)

    async def candidates(
        self, camera: str, owner: str, identifier: str, body: CandidateBody
    ) -> None:
        """Forward only ICE candidates belonging to this authorized session."""
        session = self.owned(camera, owner, identifier)
        async with session.lock:
            if not session.answered:
                raise LiveWebRTCError(409, "live_webrtc_answer_required")
            try:
                await session.socket.send_json(
                    {
                        "command": "candidate",
                        "id": session.peer_id,
                        "peer_id": session.remote_peer_id,
                        "candidates": [
                            value.model_dump(by_alias=True, exclude_none=True)
                            for value in body.candidates
                        ],
                    }
                )
            except (aiohttp.ClientError, ConnectionError):
                raise LiveWebRTCError(503, "live_webrtc_signaling_closed") from None

    async def renew(self, camera: str, owner: str, identifier: str) -> dict:
        """Renew a soft lease, never the authenticated session's hard lifetime."""
        session = self.owned(camera, owner, identifier)
        session.deadline = min(
            self.clock() + self.settings.lease_seconds, session.hard_deadline
        )
        return self._metadata(session)

    async def delete(self, camera: str, owner: str, identifier: str) -> None:
        """Close an owned viewer and remove its pipeline after the last lease."""
        session = self.sessions.get(identifier)
        if session is None or session.owner != owner or session.camera != camera:
            raise LiveWebRTCError(404, "live_webrtc_session_not_found")
        await self._end(identifier)

    async def _watch(self, session: ViewerSession) -> None:
        try:
            async for message in session.socket:
                if message.type in (
                    aiohttp.WSMsgType.ERROR,
                    aiohttp.WSMsgType.CLOSE,
                    aiohttp.WSMsgType.CLOSED,
                ):
                    break
                if message.type == aiohttp.WSMsgType.TEXT:
                    try:
                        data = json.loads(message.data)
                    except (ValueError, TypeError):
                        logger.warning("Invalid live media signaling response")
                        break
                    if not isinstance(data, dict):
                        logger.warning("Invalid live media signaling message shape")
                        break
                    if data.get("code", 200) != 200 or data.get("command") == "error":
                        logger.warning("Live media peer failed for %s", session.camera)
                        break
        except (aiohttp.ClientError, ConnectionError):
            logger.warning("Live media peer disconnected for %s", session.camera)
        finally:
            await self._end(session.identifier)

    async def _end(self, identifier: str) -> None:
        async with self.admission:
            session = self.sessions.pop(identifier, None)
        if session is None:
            return
        if (
            session.watcher is not None
            and session.watcher is not asyncio.current_task()
        ):
            session.watcher.cancel()
            await asyncio.gather(session.watcher, return_exceptions=True)
        try:
            await asyncio.wait_for(session.socket.close(), timeout=3)
        except (aiohttp.ClientError, TimeoutError):
            logger.warning("Live media signaling close timed out")
        await self._release_group(session.group)

    async def _maintain(self) -> None:
        while True:
            await asyncio.sleep(2)
            await self._maintain_once()

    async def _maintain_once(self) -> None:
        expired = []
        for session in list(self.sessions.values()):
            camera = self.config().cameras.get(session.camera)
            if (
                session.deadline <= self.clock()
                or not self.available()
                or camera is None
                or not camera.enabled
            ):
                expired.append(session.identifier)
        await asyncio.gather(*(self._end(identifier) for identifier in expired))
        for group in list(self.groups.values()):
            if group.closing and not group.users:
                async with group.lock:
                    try:
                        await self.transport.delete_pull(group)
                    except LiveWebRTCError:
                        logger.warning("Live media pipeline cleanup is still pending")
                    else:
                        async with self.admission:
                            self.groups.pop((group.camera, group.app), None)

    async def close(self) -> None:
        """Release all owned viewers and sources before stopping the private client."""
        async with self.admission:
            self.closed = True
            pending = [
                task for task in self.creating if task is not asyncio.current_task()
            ]
        for task in pending:
            task.cancel()
        await asyncio.gather(*pending, return_exceptions=True)
        if self.worker is not None:
            self.worker.cancel()
            await asyncio.gather(self.worker, return_exceptions=True)
        await asyncio.gather(
            *(self._end(identifier) for identifier in list(self.sessions))
        )
        if self.transport is not None:
            await self.transport.close()
